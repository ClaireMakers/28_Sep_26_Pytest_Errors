def make_and_return_complex_dictionary(keys, values):
    my_dict = {}
    for i in range(len(keys)):
        my_dict[keys[i]] = values[i]
    my_dict["background"] = "testing"
    del(my_dict["name"])
    return my_dict








































def triangle_number(n):
    answer = n
    while True:
        n -= 1
        answer += n
        if n < 1:
            break
    return answer








































